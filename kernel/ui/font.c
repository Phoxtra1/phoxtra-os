void font_init(void) {
    klog(LOG_INFO, "Initializing 8x16 Bitmap Font Engine...");
}

void font_draw_char(char c, uint32_t x, uint32_t y, uint32_t fg_color, uint32_t bg_color) {
    uint8_t u_c = (uint8_t)c;
    if (u_c >= 'a' && u_c <= 'z') u_c = (uint8_t)(u_c - 'a' + 'A');
    if (u_c >= 128) u_c = '?';

    const uint8_t* glyph = font_bitmap_8x16[u_c];

    for (int row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                fb_put_pixel(x + col, y + row, fg_color);
            } else if (bg_color != 0x00000000) { // Translucent background check
                fb_put_pixel(x + col, y + row, bg_color);
            }
        }
    }
}

void font_draw_string(const char* str, uint32_t x, uint32_t y, uint32_t fg_color, uint32_t bg_color) {
    if (!str) return;
    uint32_t cur_x = x;
    uint32_t cur_y = y;

    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            cur_y += 18;
        } else {
            font_draw_char(*str, cur_x, cur_y, fg_color, bg_color);
            cur_x += 9;
        }
        str++;
    }
}
