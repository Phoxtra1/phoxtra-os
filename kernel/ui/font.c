void font_draw_char(char c, uint32_t x, uint32_t y, uint32_t fg_color, uint32_t bg_color) {
    uint8_t glyph_code = (uint8_t)c;
    if (glyph_code < 0x20 || glyph_code > 0x7E) glyph_code = '?';
    const uint8_t* glyph = font_bitmap_8x8[glyph_code];

    for (uint32_t row = 0; row < 8; ++row) {
        const uint8_t bits = glyph[row];
        for (uint32_t col = 0; col < 8; ++col) {
            const uint32_t px = x + col;
            const uint32_t py = y + row * 2;
            const int set = (bits & (1u << col)) != 0;
            if (set) {
                fb_put_pixel(px, py, fg_color);
                fb_put_pixel(px, py + 1, fg_color);
            } else if (bg_color != 0) {
                fb_put_pixel(px, py, bg_color);
                fb_put_pixel(px, py + 1, bg_color);
            }
        }
    }
}

void font_draw_string(const char* str, uint32_t x, uint32_t y, uint32_t fg_color, uint32_t bg_color) {
    if (!str) return;
    uint32_t cur_x = x;
    uint32_t cur_y = y;
    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            cur_y += FONT_HEIGHT + 2;
        } else if (*str == '\r') {
            cur_x = x;
        } else if (*str == '\t') {
            cur_x += 4 * (FONT_WIDTH + 1);
        } else {
            font_draw_char(*str, cur_x, cur_y, fg_color, bg_color);
            cur_x += FONT_WIDTH + 1;
        }
        ++str;
    }
}
